import {reddit} from "@devvit/web/server";
import type {UiResponse} from "@devvit/web/shared";
import {ArchiverSettings, runModmailArchiver} from "../features/archiver.js";

export async function onArchiverFormSubmit (body: unknown): Promise<UiResponse> {
    const submission = body as {values?: Partial<ArchiverSettings>} & Partial<ArchiverSettings>;
    const config = (submission.values ?? submission) as Partial<ArchiverSettings>;

    if (typeof config.archiverNoHighlighteds !== "boolean") {
        console.error("onArchiverFormSubmit: Invalid value for archiverNoHighlighteds", config.archiverNoHighlighteds);
        return {showToast: `ERROR: Invalid value for archiverNoHighlighteds (got ${String(config.archiverNoHighlighteds)})`};
    }

    if (typeof config.archiveLastReplyUser !== "number" || config.archiveLastReplyUser <= 0) {
        console.log("onArchiverFormSubmit: Invalid value for archiveLastReplyUser", config.archiveLastReplyUser);
        return {showToast: `ERROR: Archive - Last Reply From User must be a number above 0 (got ${String(config.archiveLastReplyUser)})`};
    }

    if (typeof config.archiveLastReplyMod !== "number" || config.archiveLastReplyMod <= 0) {
        console.log("onArchiverFormSubmit: Invalid value for archiveLastReplyMod", config.archiveLastReplyMod);
        return {showToast: `ERROR: Archive - Last Reply From Mod must be a number above 0 (got ${String(config.archiveLastReplyMod)})`};
    }

    if (typeof config.archiveAutoGenerated !== "number" || config.archiveAutoGenerated <= 0) {
        console.log("onArchiverFormSubmit: Invalid value for archiveAutoGenerated", config.archiveAutoGenerated);
        return {showToast: `ERROR: Archive - Auto-Generated With No Replies must be a number above 0 (got ${String(config.archiveAutoGenerated)})`};
    }

    console.log("Running manual modmail archiver...");
    const archivedModmail = await runModmailArchiver(reddit, config as ArchiverSettings);
    console.log(`Manual archiver run finished. Archived ${archivedModmail} modmails.`);
    return {showToast: {text: `Archiver finished. Archived ${archivedModmail} modmails.`, appearance: "success"}};
}
