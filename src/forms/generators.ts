import {context, reddit} from "@devvit/web/server";
import type {Form, UiResponse} from "@devvit/web/shared";
import {ArchiverSettings} from "../features/archiver.js";
import {hasPermissions} from "../helpers.js";
import {ARCHIVE_FORM_HELP_TEXTS, ARCHIVE_FORM_LABELS} from "./strings.js";
import {getAppSettings} from "../settings/loader.js";

export async function onArchiverMenuItem (): Promise<UiResponse> {
    const userId = context.userId;
    if (!userId) {
        console.error("onArchiverMenuItem: userId is missing");
        return {showToast: "Something went wrong, please try again."};
    }

    const user = await reddit.getUserById(userId);
    if (!user) {
        console.error(`onArchiverMenuItem: No user found for ${userId}`);
        return {showToast: "Something went wrong, please try again."};
    }

    if (!await hasPermissions(reddit, {username: user.username, subredditName: context.subredditName, requiredPerms: "mail"})) {
        console.log(`onArchiverMenuItem: ${user.username} doesn't have mail permissions`);
        return {showToast: "You must have mail permissions to use this feature!"};
    }

    const config = await getAppSettings();
    return {
        showForm: {
            name: "archiverForm",
            form: createArchiverForm(config),
        },
    };
}

export function createArchiverForm (settings: ArchiverSettings): Form {
    return {
        title: ARCHIVE_FORM_LABELS.title,
        description: ARCHIVE_FORM_HELP_TEXTS.title,
        acceptLabel: ARCHIVE_FORM_LABELS.acceptLabel,
        cancelLabel: ARCHIVE_FORM_LABELS.cancelLabel,
        fields: [
            {
                type: "boolean",
                name: "archiverNoHighlighteds",
                label: ARCHIVE_FORM_LABELS.archiverNoHighlighteds,
                helpText: ARCHIVE_FORM_HELP_TEXTS.archiverNoHighlighteds,
                defaultValue: settings.archiverNoHighlighteds,
            },
            {
                type: "number",
                name: "archiveLastReplyUser",
                label: ARCHIVE_FORM_LABELS.archiveLastReplyUser,
                helpText: ARCHIVE_FORM_HELP_TEXTS.archiveLastReplyUser,
                defaultValue: settings.archiveLastReplyUser,
                required: true,
            },
            {
                type: "number",
                name: "archiveLastReplyMod",
                label: ARCHIVE_FORM_LABELS.archiveLastReplyMod,
                helpText: ARCHIVE_FORM_HELP_TEXTS.archiveLastReplyMod,
                defaultValue: settings.archiveLastReplyMod,
                required: true,
            },
            {
                type: "number",
                name: "archiveAutoGenerated",
                label: ARCHIVE_FORM_LABELS.archiveAutoGenerated,
                helpText: ARCHIVE_FORM_HELP_TEXTS.archiveAutoGenerated,
                defaultValue: settings.archiveAutoGenerated,
                required: true,
            },
        ],
    };
}
